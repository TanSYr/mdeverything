"""Markdown, SRT and JSON exporters. User text is never treated as markup."""

import html
import json
import re
from pathlib import Path
from urllib.parse import parse_qsl, quote, urlencode, urlsplit, urlunsplit

from .models import Document


def timestamp(value: float, milliseconds=False) -> str:
    secs, ms = divmod(round(value * 1000), 1000)
    hours, secs = divmod(secs, 3600)
    minutes, secs = divmod(secs, 60)
    result = f"{hours:02}:{minutes:02}:{secs:02}"
    return f"{result},{ms:03}" if milliseconds else result


def escape(text: str) -> str:
    return re.sub(r"([\\`*_{}\[\]()#+.!|>~-])", r"\\\1", html.escape(text, quote=False))


def source_link(source: str, start: float) -> str | None:
    url = urlsplit(source)
    if url.scheme not in ("http", "https"):
        return None
    query = dict(parse_qsl(url.query, keep_blank_values=True))
    host = (url.hostname or "").lower()
    if host in (
        "youtube.com",
        "www.youtube.com",
        "m.youtube.com",
        "youtu.be",
        "www.bilibili.com",
        "bilibili.com",
    ):
        query["t"] = str(int(start))
    else:
        return quote(source, safe=":/?&=%#@+;,$-_.!~*")
    return quote(
        urlunsplit((url.scheme, url.netloc, url.path, urlencode(query), "")), safe=":/?&=%#@+;,$-_.!~*"
    )


def markdown(doc: Document) -> str:
    lines = ["---"]
    for key, value in [
        ("title", doc.title),
        ("source", doc.source),
        ("language", doc.language),
        ("method", doc.method),
    ]:
        lines.append(f"{key}: {json.dumps(value, ensure_ascii=False)}")
    lines += [
        f"duration_seconds: {doc.duration:.3f}",
        "generator: mdeverything",
        "---",
        "",
        f"# {escape(doc.title)}",
        "",
    ]
    lines += [
        f"**Source:** {escape(doc.source)}",
        f"**Language:** {escape(doc.language)} · **Method:** {escape(doc.method)}",
        "",
    ]
    for warning in doc.warnings:
        lines += [f"> {escape(warning)}", ""]
    if doc.notes:
        lines += [
            "## AI notes",
            "",
            "> Generated by a local model. Verify against the transcript.",
            "",
            escape(doc.notes),
            "",
        ]
    if doc.chapters:
        lines += ["## Chapters", ""]
        for chapter in sorted(doc.chapters, key=lambda c: c["start"]):
            label = timestamp(chapter["start"])
            link = source_link(doc.source, chapter["start"])
            anchor = f"[{label}]({link})" if link else label
            lines.append(f"- {anchor} — {escape(chapter['title'])}")
        lines.append("")
    lines += ["## Transcript", ""]
    for segment in doc.segments:
        label = timestamp(segment.start)
        link = source_link(doc.source, segment.start)
        anchor = f"[{label}]({link})" if link else label
        lines += [f"**{anchor}**", "", escape(segment.text), ""]
    return "\n".join(lines)


def srt(doc: Document) -> str:
    return (
        "\n\n".join(
            f"{i}\n{timestamp(s.start, True)} --> {timestamp(s.end, True)}\n{s.text}"
            for i, s in enumerate(doc.segments, 1)
        )
        + "\n"
    )


def write_document(doc: Document, directory: Path) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    files = {
        "document.md": markdown(doc),
        "document.srt": srt(doc),
        "document.json": json.dumps(doc.to_dict(), ensure_ascii=False, indent=2),
    }
    for name, content in files.items():
        temp = directory / (name + ".tmp")
        temp.write_text(content, encoding="utf-8")
        temp.replace(directory / name)
